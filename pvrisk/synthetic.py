def make(start="2006-01-02", end="2026-11-04", seed=7):
    rng = np.random.default_rng(seed)
    idx = pd.bdate_range(start, end)
    n = len(idx)
    # GARCH(1,1)-유사 공통 변동성 배수
    vol = np.empty(n)
    v = 1.0
    shocks = rng.standard_t(5, size=n) / np.sqrt(5 / 3)
    for i in range(n):
        v = np.sqrt(0.02 + 0.90 * v**2 + 0.08 * (shocks[i - 1] ** 2 if i else 1.0))
        vol[i] = min(v, 4.0)
    for a, b, m in [("2008-09-15", "2009-03-31", 2.5), ("2020-02-24", "2020-04-30", 3.0), ("2022-01-03", "2022-10-31", 1.4)]:
        mask = (idx >= a) & (idx <= b)
        vol[mask] *= m
    d = 1 / 252
    mkt = shocks * vol * 0.17 * np.sqrt(d)
    tech = rng.standard_normal(n) * vol * 0.10 * np.sqrt(d)
    semi = rng.standard_normal(n) * vol * 0.16 * np.sqrt(d)
    soft = rng.standard_normal(n) * vol * 0.12 * np.sqrt(d)
    rate = rng.standard_normal(n) * 0.12 * np.sqrt(d)
    gold = rng.standard_normal(n) * 0.14 * np.sqrt(d)
    # 주식-채권: 2000년대~2021 음(-)의 상관, 2022~ 양(+)
    sb = np.where(idx < "2022-01-01", -0.35, 0.45)
    rate = rate + sb * mkt * 0.6
    # 2026년 반도체-소프트웨어 디커플링: 테크 공통요인이 소프트웨어에서 반대로 작동
    decouple = (idx >= "2026-01-02")
    soft_sign = np.where(decouple, -0.9, 1.0)

    px = {}
    for t, (mu, sig, beta, ft, fs, fw, fr, fg, ipo) in SPEC.items():
        if t == "SGOV":
            continue
        sys = beta * mkt + ft * tech + fs * semi + fw * soft_sign * tech * 0.9 + fw * soft + fr * rate + fg * gold
        sys_var = np.var(sys) / d
        idio_sd = np.sqrt(max(sig**2 - sys_var, (0.15 * sig) ** 2))
        idio = rng.standard_normal(n) * idio_sd * np.sqrt(d) * np.sqrt(vol)
        r = mu * d + sys + idio
        if t == "MU":
            r[(idx >= "2026-06-22")] -= 0.0025  # 최근 반도체 급락 흉내
        if t in ("SOXX",):
            r[(idx >= "2026-06-22")] -= 0.0012
        p = 100 * np.exp(np.cumsum(np.log1p(np.clip(r, -0.6, 2))))
        s = pd.Series(p, idx, name=t)
        if ipo:
            s[s.index < ipo] = np.nan
        px[t] = s
    px = pd.DataFrame(px)
    # T-bill: 단순 금리 경로
    y = np.interp(np.arange(n), [0, n * 0.12, n * 0.17, n * 0.55, n * 0.78, n * 0.83, n * 0.9, n - 1],
                  [0.045, 0.05, 0.002, 0.001, 0.0015, 0.045, 0.053, 0.039])
    tb = pd.Series(y, idx, name="TBILL_YLD")
    sg = (1 + tb * 1 / 360 * pd.Series(idx, index=idx).diff().dt.days.fillna(1)).cumprod() * 100
    sg[sg.index < "2020-05-26"] = np.nan
    px["SGOV"] = sg
    # 환율: 위험회피 시 원화 약세(미 주식과 음의 상관)
    fx_r = -0.25 * mkt + rng.standard_normal(n) * 0.07 * np.sqrt(d)
    fx = pd.Series(1100 * np.exp(np.cumsum(fx_r)), idx, name="USDKRW")
    fx = fx * (1400 / fx.iloc[-1])
    return px, tb, fx
